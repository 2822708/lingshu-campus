// Returns percentage increase (0.1 = 10%)
export const getUpgradeMultiplier = (rarity: ItemRarity = '普通') => {
  switch (rarity) {
    case '普通':
      return 0.1;
    case '稀有':
      return 0.15;
    case '传说':
      return 0.2;
    case '绝版':
      return 0.25;
    default:
      return 0.1;
  }
};

